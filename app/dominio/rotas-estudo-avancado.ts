function normalizar(texto: string): string { return texto.normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim(); }

function chave(item: ConceitoIndexado): string { return normalizar([item.conceito.nome,item.conceito.nomeOriginal,item.conceito.id,...item.aliases].filter(Boolean).join(' ')); }

function localizar(indice: ConceitoIndexado[], termos: string[]): ConceitoIndexado[] { const mapa=new Map<string,ConceitoIndexado>(); for (const termoBruto of termos){ const termo=normalizar(termoBruto); if(!termo) continue; indice.filter(item=>chave(item).includes(termo)).slice(0,6).forEach(item=>mapa.set(item.conceito.id,item)); } return [...mapa.values()].slice(0,8); }

