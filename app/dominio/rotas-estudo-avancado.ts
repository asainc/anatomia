export function resolverRotasEstudoAvancado(indice: ConceitoIndexado[]): RotaEstudoResolvida[] { return ROTAS_ESTUDO_AVANCADO.map(rota=>{ const etapas=rota.etapas.map(etapa=>({...etapa,conceitos:localizar(indice,etapa.termos)})); const ids=new Set(etapas.flatMap(e=>e.conceitos.map(c=>c.conceito.id))); return {...rota,etapas,totalConceitos:ids.size}; }); }

