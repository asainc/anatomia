function normalizar(texto: string): string {
  return texto
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

function chaveBusca(item: ConceitoIndexado): string {
  return normalizar([
    item.conceito.id,
    item.conceito.nome,
    item.conceito.nomeOriginal,
    ...item.aliases,
  ].filter(Boolean).join(' '));
}

function localizarConceitos(indice: ConceitoIndexado[], termos: string[]): ConceitoIndexado[] {
  const encontrados = new Map<string, ConceitoIndexado>();
  const normalizados = termos.map(normalizar).filter(Boolean);

  normalizados.forEach((termo) => {
    indice
      .filter((item) => chaveBusca(item).includes(termo))
      .sort((a, b) => a.conceito.nome.localeCompare(b.conceito.nome, 'pt-BR'))
      .forEach((item) => {
        if (!encontrados.has(item.conceito.id)) encontrados.set(item.conceito.id, item);
      });
  });

  return [...encontrados.values()];
}

