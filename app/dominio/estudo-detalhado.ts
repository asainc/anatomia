export function resolverFichasEstudoDetalhado(indice: ConceitoIndexado[]): FichaEstudoResolvida[] {
  return FICHAS_ESTUDO_DETALHADO.map((ficha) => ({
    ...ficha,
    conceitosRelacionados: localizarConceitos(indice, [
      ...ficha.estruturasChave,
      ...ficha.gatilhos,
    ]).slice(0, 16),
  }));
}

function pontuarRelacionamento(ficha: FichaEstudoResolvida, item: ConceitoIndexado): number {
  const texto = chaveBusca(item);
  let pontos = 0;

  if (ficha.sistema && ficha.sistema === item.sistema) pontos += 3;
  if (ficha.regiao && ficha.regiao === item.regiao) pontos += 2;
  if (ficha.conceitosRelacionados.some((rel) => rel.conceito.id === item.conceito.id)) pontos += 10;

  ficha.gatilhos.forEach((gatilho) => {
    if (texto.includes(normalizar(gatilho))) pontos += 4;
  });
  ficha.estruturasChave.forEach((termo) => {
    if (texto.includes(normalizar(termo))) pontos += 5;
  });

  return pontos;
}

export function fichasRelacionadasAoConceito(
  fichas: FichaEstudoResolvida[],
  item: ConceitoIndexado,
  limite = 5,
): FichaEstudoResolvida[] {
  return fichas
    .map((ficha) => ({ficha, pontos: pontuarRelacionamento(ficha, item)}))
    .filter(({pontos}) => pontos >= 5)
    .sort((a, b) => b.pontos - a.pontos || a.ficha.titulo.localeCompare(b.ficha.titulo, 'pt-BR'))
    .slice(0, limite)
    .map(({ficha}) => ficha);
}
